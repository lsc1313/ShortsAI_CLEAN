import {
    callAI
} from "../ai/index.js";

import {
    parseJSON
} from "../ai/utils.js";


function cleanText(value = "") {

    return String(
        value ?? ""
    ).trim();

}


function cleanArray(value) {

    if (!Array.isArray(value)) {

        return [];

    }

    return value
        .map(item =>
            cleanText(item)
        )
        .filter(Boolean);

}


function cleanSections(value) {

    if (!Array.isArray(value)) {

        return [];

    }

    return value
        .map(item => ({

            heading:
                cleanText(
                    item?.heading
                ),

            body:
                cleanText(
                    item?.body
                )

        }))
        .filter(item =>
            item.heading &&
            item.body
        )
        .slice(0, 3);

}


export async function createBlogContent(
    product
) {

    if (!product) {

        throw new Error(
            "BlogAI: 상품 정보가 없습니다."
        );

    }


    const productName =
        cleanText(
            product.name
        );


    if (!productName) {

        throw new Error(
            "BlogAI: 상품명이 없습니다."
        );

    }


    /*
    =====================================================
    FACT DATA

    AI가 상품의 실제 사실로 사용할 수 있는 데이터.
    =====================================================
    */

    const facts = {

        name:
            productName,

        keyword:
            cleanText(
                product.keyword
            ),

        description:
            cleanText(
                product.description
            ),

        category:
            cleanText(
                product.category
            )

    };


    const prompt = `
너는 한국어 쇼핑 블로그를 작성하는 전문 에디터다.

이번 글의 목표는
상품 정보를 기계적으로 나열하는 것이 아니다.

실제 사람이 상품을 알아보고
구매 전에 정리해주는 것처럼

읽기 편하고,
자연스럽고,
정보가 잘 정리된
한국어 블로그 글을 작성한다.

단,

실제로 사용하지 않은 상품을
사용했다고 말해서는 안 된다.

확인되지 않은 상품 스펙이나 장점을
사실처럼 만들어서도 안 된다.


==================================================
[확인된 상품 데이터]
==================================================

상품명:
${facts.name}

등록 키워드:
${facts.keyword || "정보 없음"}

상품 설명:
${facts.description || "정보 없음"}

카테고리:
${facts.category || "정보 없음"}


==================================================
[가장 중요한 작성 원칙]
==================================================

이 글은

"상품 정보 및 구매 전 확인 사항"

같은 설명서가 아니다.

사람이 읽는 실제 블로그 글처럼 작성한다.


좋은 흐름의 예:

상품을 찾게 되는 상황
→
상품을 살펴볼 때 눈여겨볼 부분
→
구매할 때 비교해야 할 기준
→
어떤 상황에서 살펴볼 만한지
→
마지막 구매 전 확인사항

단,

실제 사용 후기처럼 꾸며서는 안 된다.


==================================================
[절대 규칙]
==================================================

1.

위 "확인된 상품 데이터"에 없는
구체적인 상품 사실을 만들어내지 않는다.


2.

상품명만 보고 다음 내용을 추측하지 않는다.

- 재질
- 원료
- 크기
- 용량
- 수량
- 제조 방식
- 성능
- 기능
- 인증
- 원산지
- 제조국
- 구성품
- 두께
- 향
- 흡수력
- 내구성
- 피부 자극
- 먼지 발생 정도


3.

가격,
정상가,
할인가,
할인율,
쿠폰,
배송비,
배송 속도,
재고를 만들어내지 않는다.


4.

다음과 같은 가짜 체험 표현을 사용하지 않는다.

- 직접 사용해봤다
- 사용해보니
- 제가 써봤는데
- 실제로 써보니
- 써보니까
- 구매해서 사용했다


5.

검증되지 않은 다음 표현을 사용하지 않는다.

- 인기 제품
- 베스트셀러
- 판매 1위
- 국민 제품
- 많은 소비자가 선택
- 가장 좋은
- 최고의
- 무조건 추천


6.

상품명으로 확인할 수 없는 장점을
상품의 실제 장점이라고 단정하지 않는다.


7.

상품 정보가 부족하면
억지로 내용을 만들어내지 않는다.

대신

이 상품군을 구매할 때
소비자가 실제 판매 페이지에서
무엇을 비교하고 확인하면 좋은지
구체적으로 설명한다.


8.

의학적,
건강상,
치료,
예방 효능을 만들어내지 않는다.


9.

쿠팡 URL이나
외부 링크를 생성하지 않는다.


10.

동일한 상품명이나 키워드를
SEO 목적으로 부자연스럽게 반복하지 않는다.


11.

"판매 페이지에서 확인하세요"라는 말만
계속 반복하지 않는다.

왜 그 항목을 확인해야 하는지까지
간단하게 설명한다.


12.

문장은 지나치게 딱딱한
보고서 문체를 피한다.


13.

그렇다고 과도한 감탄사,
이모지,
과장 광고 문구도 사용하지 않는다.


14.

상품에 대한 정보와
일반적인 구매 가이드를 명확히 구분한다.


==================================================
[제목 작성]
==================================================

검색 결과에서 상품과 글의 내용을
쉽게 이해할 수 있으면서도
사람이 작성한 블로그 제목처럼 만든다.

매번

"상품 정보 및 구매 전 확인 사항"
"구매 전 체크포인트"
"상품 알아보기"

같은 제목을 반복하지 않는다.


가능한 스타일 예시:

"OO 고를 때 뭘 봐야 할까? 구매 전에 살펴볼 포인트"

"OO 알아보는 중이라면? 구매 전에 체크할 부분"

"OO 살펴보기, 선택 전에 확인하면 좋은 기준"

"OO 구매할 때 놓치기 쉬운 체크포인트"


상품 특성에 따라 자연스럽게 변형한다.

과장형 클릭베이트는 금지한다.


==================================================
[INTRO]
==================================================

3~5문장.

첫 문장부터

"본 포스팅에서는"
"이 글에서는"
"상품 정보를 알아보겠습니다"

같은 기계적인 표현으로 시작하지 않는다.

상품 유형을 찾게 되는
일상적인 상황이나
구매 고민에서 자연스럽게 시작한다.

실제 사용 경험은 만들지 않는다.


==================================================
[SECTIONS]
==================================================

본문 섹션은 정확히 3개 작성한다.

각 섹션은

heading
body

구조다.


heading:

상품 특성이나 구매 포인트에 맞는
자연스러운 블로그 소제목.

모든 상품에서 같은 제목을
반복하지 않는다.


body:

각 섹션 3~6문장.

단순 체크리스트가 아니라
왜 살펴봐야 하는지
독자가 이해할 수 있게 설명한다.


섹션의 전체적인 역할은 다음과 같다.

SECTION 1

현재 확인 가능한 상품 정보와
상품을 볼 때 먼저 살펴볼 부분.


SECTION 2

해당 상품군을 비교하거나
선택할 때 중요한 구매 기준.


SECTION 3

실제 구매 직전에
옵션이나 구성 등을 비교하는 방법.


하지만 위 역할 이름을
그대로 heading으로 사용하지 않는다.


==================================================
[CHECK POINTS]
==================================================

구매자가 실제로 비교할 수 있는
체크포인트 3~5개.

각 항목은 너무 길지 않게 작성한다.

단순히

"상세페이지 확인"
"옵션 확인"

이라고 끝내지 말고

무엇을 확인해야 하는지가
드러나도록 작성한다.


==================================================
[RECOMMENDATION]
==================================================

"이런 분이라면 살펴볼 만해요"

성격의 내용.

확인되지 않은 성능을 근거로
추천하지 않는다.

2~4문장.


==================================================
[FAQ]
==================================================

구매자가 실제 검색하거나
궁금해할 가능성이 있는 질문 3개.

확인되지 않은 상품 사실은
답변에 넣지 않는다.

답변은 단순히
"상세페이지를 확인하세요"
한 문장으로 끝내지 않는다.

확인해야 할 항목과
그 이유를 함께 설명한다.


==================================================
[CLOSING]
==================================================

글을 자연스럽게 마무리하는
2~4문장.

앞의 내용을 그대로 반복하지 않는다.

구매 전에
현재 옵션,
구성,
가격,
배송 조건 등을
최종적으로 비교해야 한다는 내용을
자연스럽게 포함할 수 있다.

광고성 구매 압박 표현은 금지한다.


==================================================
[TAGS]
==================================================

상품명,
상품 유형,
구매 관련 검색어를 중심으로
5~8개 작성한다.

# 문자는 넣지 않는다.


==================================================
[출력]
==================================================

설명,
마크다운,
코드블록 없이

JSON 하나만 출력한다.

{
  "title": "",
  "intro": "",
  "sections": [
    {
      "heading": "",
      "body": ""
    },
    {
      "heading": "",
      "body": ""
    },
    {
      "heading": "",
      "body": ""
    }
  ],
  "checkPoints": [
    "",
    "",
    ""
  ],
  "recommendation": "",
  "faq": [
    {
      "question": "",
      "answer": ""
    },
    {
      "question": "",
      "answer": ""
    },
    {
      "question": "",
      "answer": ""
    }
  ],
  "closing": "",
  "tags": [
    ""
  ]
}
`;


    /*
    =====================================================
    BLOG AI CALL

    전체 블로그 생성에서 AI 호출은 이 1회뿐이다.
    =====================================================
    */

    const response =
        await callAI(
            prompt
        );


    const parsed =
        parseJSON(
            response
        );


    if (
        !parsed ||
        typeof parsed !== "object"
    ) {

        throw new Error(
            "BlogAI: AI 응답 파싱 실패"
        );

    }


    const sections =
        cleanSections(
            parsed.sections
        );


    if (sections.length < 3) {

        throw new Error(
            `BlogAI: 본문 섹션 부족 (${sections.length}/3)`
        );

    }


    const checkPoints =
        cleanArray(
            parsed.checkPoints
        )
        .slice(0, 5);


    const faq =
        Array.isArray(
            parsed.faq
        )
            ? parsed.faq
                .map(item => ({

                    question:
                        cleanText(
                            item?.question
                        ),

                    answer:
                        cleanText(
                            item?.answer
                        )

                }))
                .filter(item =>
                    item.question &&
                    item.answer
                )
                .slice(0, 3)

            : [];


    const tags =
        cleanArray(
            parsed.tags
        )
        .map(tag =>
            tag.replace(
                /^#+/,
                ""
            ).trim()
        )
        .filter(Boolean)
        .slice(0, 8);


    return {

        title:
            cleanText(
                parsed.title
            ) ||
            `${productName} 구매 전에 살펴볼 포인트`,

        intro:
            cleanText(
                parsed.intro
            ),

        sections,

        checkPoints,

        recommendation:
            cleanText(
                parsed.recommendation
            ),

        faq,

        closing:
            cleanText(
                parsed.closing
            ),

        tags

    };

}


