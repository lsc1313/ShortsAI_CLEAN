    const response = await callAI(prompt);

    const parsed = parseJSON(response);

    if (
        !parsed ||
        typeof parsed !== "object"
    ) {
        throw new Error(
            "ScienceBlogAI: AI 응답 파싱 실패"
        );
    }

    const sections = cleanSections(
        parsed.sections
    );

    if (sections.length < 4) {
        throw new Error(
            `ScienceBlogAI: 본문 섹션 부족 (${sections.length}/4)`
        );
    }

    const faq = cleanFAQ(
        parsed.faq
    );

    const imageQueries = cleanArray(
        parsed.imageQueries
    ).slice(0, 2);

    const tags = cleanArray(
        parsed.tags
    )
        .map(tag =>
            tag
                .replace(/^#+/, "")
                .trim()
        )
        .filter(Boolean)
        .slice(0, 8);

    return {
        title:
            cleanText(parsed.title) ||
            topic,

        intro:
            cleanText(parsed.intro),

        sections,

        checkPoints:
            cleanArray(parsed.checkPoints)
                .slice(0, 5),

        faq,

        closing:
            cleanText(parsed.closing),

        imageQueries,

        tags
    };
