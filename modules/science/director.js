export async function createScienceDirector(
    topic = ""
){

    console.log(
        "[SCIENCE DIRECTOR] START"
    );


    /*
    =================================================
    1.
    키워드 → 완성 주제 + 유형 판단
    =================================================
    */

    const judgePrompt =
        TYPE_JUDGE_PROMPT.replace(
            "{{TOPIC}}",
            String(topic || "")
        );


    const judgeResult =
        await callAI(
            judgePrompt
        );


    const judge =
        parseJSON(
            judgeResult
        );


    const format = "global";

        const completedTopic =
        String(
            judge?.completedTopic ||
            topic ||
            ""
        ).trim();


    console.log(
        `[SCIENCE DIRECTOR] FORMAT : ${format}`
    );


    console.log(
        `[SCIENCE DIRECTOR] TOPIC : ${completedTopic}`
    );


    /*
    =================================================
    2.
    선택된 유형 전용 Director Prompt
    =================================================
    */

    const typePrompt = GLOBAL_PROMPT;

        const finalPrompt = `

${COMMON_PROMPT}

${typePrompt}

=====================================================
DIRECTOR INPUT
=====================================================

Manager Keywords:

${topic}


Director Completed Topic:

${completedTopic}


선택된 콘텐츠 형식:

${format}


위 정보를 바탕으로 최종 Shorts Director 결과를 만든다.


중요:

completedTopic을 그대로 반복하는 것이 아니라
실제 영상에서 사용할 수 있도록
대본과 장면을 구성한다.


모든 Scene에는 다음 필드를 빠짐없이 넣는다.

type
script
tts
subtitle
visualType
imageQueries
direction
shot
cameraMove
motion
transition
duration
sceneType


JSON 외에는 절대 출력하지 않는다.
`;


    /*
    =================================================
    3.
    최종 Director 실행
    =================================================
    */

    const result =
        await callAI(
            finalPrompt
        );


    console.log(
        "===== SCIENCE DIRECTOR RESULT ====="
    );


    console.log(
        result
    );


    console.log(
        "==================================="
    );


    const director =
        parseJSON(
            result
        );


    /*
    =================================================
    4.
    안전 보정
    =================================================
    */

    director.title =
        String(
            director.title ||
            completedTopic
        ).trim();


    director.description =
        "";


    director.format =
        format;


    director.scenes =
        director
            .work_instructions
            ?.scenes ||
        director
            .director_analysis
            ?.work_instructions
            ?.scenes ||
        [];


    /*
    =================================================
    5.
    SCENE SAFETY NORMALIZATION
    =================================================
    */

    for(
        const scene of director.scenes
    ){

        /*
        모든 Scene은 visualType = scene
        */

        scene.visualType =
            "scene";


        /*
        Ending은 반드시 ending
        */

        if(
            scene.type === "ending"
        ){

            scene.sceneType =
                format;

        }
        else{

            scene.sceneType =
                format;

        }


        /*
        imageQueries가 없으면 배열 생성
        */

        if(
            !Array.isArray(
                scene.imageQueries
            )
        ){

            scene.imageQueries = [];

        }


    }

    return director;
}
